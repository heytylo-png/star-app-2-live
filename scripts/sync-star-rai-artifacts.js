#!/usr/bin/env node
/**
 * Bake artifacts/star-rai-*.txt (+ star-chart-v1.txt + star-life-one-pager.txt
 * + star-rai-pose-tint.txt + star-rai-shell.txt + star-rai-call-mode.txt)
 * into a TS module so RAI_SYSTEM, the local-brain fallback, the memory-slots
 * contract, Chart v1, Life v1, pose tint, the 3-tab shell, and Call mode
 * cannot drift from the files on disk.
 *
 * Mirrors Expo Companion `scripts/sync-star-rai-artifacts.js`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactsDir = path.join(root, "artifacts");
const outDir = path.join(root, "src/lib/generated");
const outFile = path.join(outDir, "star-rai-artifacts.ts");

const VOICE = "star-rai-voice-card.txt";
const BRAIN = "star-rai-local-brain.txt";
const SLOTS = "star-rai-memory-slots.txt";
const CHART = "star-chart-v1.txt";
const LIFE = "star-life-one-pager.txt";
const TINT = "star-rai-pose-tint.txt";
const SHELL = "star-rai-shell.txt";
const CALL = "star-rai-call-mode.txt";

function readExact(name) {
  const file = path.join(artifactsDir, name);
  if (!fs.existsSync(file)) {
    throw new Error(`Missing artifact: artifacts/${name}`);
  }
  return fs.readFileSync(file, "utf8");
}

const voice = readExact(VOICE);
const brain = readExact(BRAIN);
const slots = readExact(SLOTS);
const chart = readExact(CHART);
const life = readExact(LIFE);
const tint = readExact(TINT);
const shell = readExact(SHELL);
const call = readExact(CALL);

if (!voice.includes("STAR RAI — VOICE CARD")) {
  throw new Error(`${VOICE} does not look like the Star Rai voice card`);
}
if (!brain.includes("pose_key | emotion | line")) {
  throw new Error(`${BRAIN} does not look like the local-brain table`);
}
if (!slots.includes("STAR RAI — MEMORY SLOTS")) {
  throw new Error(`${SLOTS} does not look like the memory-slots contract`);
}
if (!chart.includes("STAR RAI — CHART v1")) {
  throw new Error(`${CHART} does not look like the Chart v1 spec`);
}
if (!life.includes("STAR RAI — LIFE v1")) {
  throw new Error(`${LIFE} does not look like the Life v1 spec`);
}
if (!tint.includes("STAR RAI — POSE TINT")) {
  throw new Error(`${TINT} does not look like the pose-tint spec`);
}
if (!shell.includes("STAR RAI — 3-TAB SHELL")) {
  throw new Error(`${SHELL} does not look like the 3-tab shell spec`);
}
if (!call.includes("STAR RAI — CALL MODE")) {
  throw new Error(`${CALL} does not look like the Call mode spec`);
}

fs.mkdirSync(outDir, { recursive: true });

const header = `/* AUTO-GENERATED by scripts/sync-star-rai-artifacts.js — do not edit.
 * Source of truth: artifacts/${VOICE} + artifacts/${BRAIN} + artifacts/${SLOTS} + artifacts/${CHART} + artifacts/${LIFE} + artifacts/${TINT} + artifacts/${SHELL} + artifacts/${CALL}
 */
`;

const body = `${header}export const RAI_SYSTEM: string = ${JSON.stringify(voice)};

export const LOCAL_BRAIN_SOURCE: string = ${JSON.stringify(brain)};

export const MEMORY_SLOTS_CONTRACT: string = ${JSON.stringify(slots)};

export const CHART_V1_SOURCE: string = ${JSON.stringify(chart)};

export const LIFE_V1_SOURCE: string = ${JSON.stringify(life)};

export const POSE_TINT_SOURCE: string = ${JSON.stringify(tint)};

export const SHELL_SOURCE: string = ${JSON.stringify(shell)};

export const CALL_MODE_SOURCE: string = ${JSON.stringify(call)};
`;

fs.writeFileSync(outFile, body);
console.log(
  `synced ${path.relative(root, outFile)} (${voice.length} + ${brain.length} + ${slots.length} + ${chart.length} + ${life.length} + ${tint.length} + ${shell.length} + ${call.length} chars)`,
);
