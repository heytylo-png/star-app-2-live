# step 9: write src/lib/welcome-clip-edges.json from the shipped files (ffmpeg decode of the AVIF alpha track):
# per clip sha256 / frame count / band size, max alpha on a 2 px strip at the band's left, right and bottom edge per frame,
# and each frame's alpha bbox (alpha > T) in 720x1280 sheet space. Rebuilt 2026-10-14 (reproduces the wb2 entries).
import subprocess,numpy as np,json,hashlib,sys
R='/workspace/r67/'; T=int(sys.argv[1]) if len(sys.argv)>1 else 0
FILES=['rai/welcome1329.avif','rai/welcome1330.avif','rai/welcome1366.avif']
def alpha(p):
    r=subprocess.run(['ffmpeg','-v','error','-i',p,'-map','0:3','-f','rawvideo','-pix_fmt','gray','-'],capture_output=True,check=True).stdout
    return np.frombuffer(r,np.uint8).reshape(-1,1280,672)
out=dict(note='Generated by bridge/wbpipe/gen_edges.py from the shipped files (ffmpeg decode of the AVIF alpha track). Do not edit by hand.',box=dict(x=0,y=0,w=672,h=1280),strip_px=2,clips={})
for f in FILES:
    p=R+'public/'+f
    try: A=alpha(p)
    except Exception: continue
    fe=[]
    for i,a in enumerate(A):
        ys,xs=np.nonzero(a>T)
        fe.append(dict(i=i,left=int(a[:,:2].max()),right=int(a[:,-2:].max()),bottom=int(a[-2:].max()),bbox=[int(xs.min()),int(ys.min()),int(xs.max()),int(ys.max())]))
    out['clips'][f]=dict(sha256=hashlib.sha256(open(p,'rb').read()).hexdigest(),frames=len(A),width=672,height=1280,frame_edges=fe)
    print(f,len(A),'max l/r/b',max(x['left'] for x in fe),max(x['right'] for x in fe),max(x['bottom'] for x in fe))
json.dump(out,open(sys.argv[2] if len(sys.argv)>2 else R+'src/lib/welcome-clip-edges.json','w'),indent=0)
